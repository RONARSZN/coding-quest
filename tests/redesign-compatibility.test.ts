import { describe, expect, it } from "vitest";
import legacyRaw from "./fixtures/redesign-v3.json?raw";
import { pack, quests, questById, skills } from "../src/curriculum";
import {
  blankProgress,
  completeAttempt,
  completed,
  createAttempt,
  fingerprint,
  hasBossEvidence,
  latest,
  unlocked,
  updateAttempt,
  xp,
} from "../src/domain";
import { load, parseProgress, save } from "../src/storage";
import type { Attempt, Progress, Quest } from "../src/types";

type LegacySnapshot = {
  originalPack: { id: string; version: number };
  contracts: Pick<Quest, "id" | "version" | "kind" | "fresh" | "checks" | "skills" | "prerequisites" | "gate">[];
  skillIds: string[];
  previouslyUnlocked: string[];
  progress: Progress;
};

// Frozen from the copied v3 source, rather than regenerated by the redesigned app.
const legacy = JSON.parse(legacyRaw) as LegacySnapshot;
const legacyIds = new Set(legacy.contracts.map((q) => q.id));
const additions = quests.filter((q) => !legacyIds.has(q.id));
const date = "2026-10-21T04:00:00.000Z";
const stableFields = ["attempts", "evidence", "awards", "reviews", "journal", "settings"] as const;

function memoryStore() {
  let raw: string | null = null;
  return {
    read: () => raw,
    write: (value: string) => { raw = value; },
  };
}

function pass(p: Progress, q: Quest, patch: Partial<Attempt> = {}): Progress {
  const a: Attempt = {
    ...createAttempt(p, q, date),
    code: { ...q.solution },
    prediction: "Fixture prediction before running",
    reflection: "Fixture: compared actual behavior with the requirement",
    explanation: "Fixture: explained the input, rule, and output",
    bug: "Fixture: reproduced and repaired the boundary mismatch",
    rubric: [true, true, true, true],
    ...patch,
    checks: q.checks.map((c) => ({
      id: c.id, label: c.label, passed: true, detail: "Domain fixture; execution verified separately",
    })),
  };
  a.checkedCode = fingerprint(a);
  return completeAttempt(p, a, q, date);
}

function prepare(p: Progress, q: Quest): Progress {
  let next = p;
  for (const id of q.prerequisites) {
    if (!completed(next, id)) {
      const prerequisite = questById(id)!;
      next = pass(prepare(next, prerequisite), prerequisite);
    }
  }
  if (q.gate && !hasBossEvidence(next, q.gate)) {
    const fresh = questById(`${q.gate}-fresh`)!;
    next = pass(prepare(next, fresh), fresh);
  }
  return next;
}

describe("redesign preserves the frozen pre-redesign content contract", () => {
  it("retains old behavior checks, identities, evidence meaning, and prerequisites", () => {
    expect(legacy.contracts).toHaveLength(27);
    for (const before of legacy.contracts) {
      const current = questById(before.id);
      expect(current, before.id).toBeDefined();
      expect(current!.version, before.id).toBeGreaterThanOrEqual(before.version);
      for (const field of ["checks", "kind", "fresh", "skills", "prerequisites", "gate"] as const)
        expect(current![field], `${before.id}: ${field}`).toEqual(before[field]);
    }
    expect(skills.map((s) => s.id)).toEqual(expect.arrayContaining(legacy.skillIds));
  });

  it("upgrades only pack metadata while preserving every old learner record", () => {
    expect(legacy.originalPack.version).toBe(3);
    expect(pack.version).toBeGreaterThan(legacy.originalPack.version);
    const restored = parseProgress(JSON.stringify(legacy.progress));
    expect(restored.schemaVersion).toBe(1);
    expect(restored.packs[legacy.originalPack.id]).toBe(pack.version);
    for (const field of stableFields) expect(restored[field]).toEqual(legacy.progress[field]);
    expect(xp(restored)).toBe(xp(legacy.progress));
    expect(parseProgress(JSON.stringify(restored))).toEqual(restored);
    for (const id of legacy.previouslyUnlocked)
      expect(unlocked(restored, questById(id)!), id).toBe(true);
  });

  it("loads and resumes the old unfinished draft including archived solution exposure", () => {
    const restored = parseProgress(JSON.stringify(legacy.progress));
    const store = memoryStore();
    expect(save(restored, store)).toBe("");
    const reloaded = load(store);
    expect(reloaded.error).toBe("");
    expect(reloaded.progress).toEqual(restored);
    expect(latest(reloaded.progress, "q06")).toEqual(latest(legacy.progress, "q06"));
    expect(createAttempt(reloaded.progress, questById("q06")!, date).solution).toBe(true);
  });

  it("retains old awards exactly when an old completed quest is practiced again", () => {
    const restored = parseProgress(JSON.stringify(legacy.progress));
    const repeated = pass(restored, questById("q01")!);
    expect(repeated.awards).toEqual(legacy.progress.awards);
    expect(xp(repeated)).toBe(xp(legacy.progress));
    expect(parseProgress(JSON.stringify(repeated)).awards).toEqual(legacy.progress.awards);
  });
});

describe("new curriculum uses the existing restorable progress model", () => {
  it("adds authored learning activities rather than relabeling old identifiers", () => {
    expect(additions.length).toBeGreaterThan(0);
    expect(additions.every((q) => q.checks.length > 0)).toBe(true);
  });

  it.each(additions)("$id unfinished code and assistance survive save and reload", (q) => {
    const p = prepare(blankProgress(), q);
    const a: Attempt = {
      ...createAttempt(p, q, date),
      code: { ...q.starter, js: `${q.starter.js}\n// An unfinished private draft` },
      prediction: "My unfinished prediction",
      reflection: "A reflection draft",
      explanation: "My own partial explanation",
      nextStep: "Resume one small change",
      hints: 2,
      solution: true,
    };
    const draft = updateAttempt(p, a);
    const store = memoryStore();
    expect(save(draft, store)).toBe("");
    expect(load(store).error).toBe("");
    expect(load(store).progress).toEqual(draft);
    const reset = updateAttempt(draft, { ...a, archived: true });
    expect(createAttempt(reset, q, date).solution).toBe(true);
  });

  it.each(additions)("$id completed records round-trip without duplicate XP", (q) => {
    const p = prepare(blankProgress(), q);
    expect(unlocked(p, q)).toBe(true);
    const first = pass(p, q);
    const restored = parseProgress(JSON.stringify(first));
    expect(restored).toEqual(first);
    const repeated = pass(restored, q);
    expect(repeated.awards).toEqual(first.awards);
    expect(xp(repeated)).toBe(xp(first));
    expect(parseProgress(JSON.stringify(repeated))).toEqual(repeated);
  });
});
